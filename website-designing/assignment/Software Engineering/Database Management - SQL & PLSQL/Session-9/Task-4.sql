CREATE TABLE wallets (
    user_id INT PRIMARY KEY,
    balance DECIMAL(10,2) NOT NULL CHECK (balance >= 0)
);

CREATE TABLE WalletTransactions (
    txn_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT,
    amount DECIMAL(10,2) NOT NULL,
    txn_type VARCHAR2(10) NOT NULL CHECK (txn_type IN ('DEBIT', 'CREDIT')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES wallets(user_id)
);

CREATE OR REPLACE TRIGGER trg_after_wallet_transaction
AFTER INSERT ON WalletTransactions
FOR EACH ROW
BEGIN
    IF :NEW.txn_type = 'DEBIT' THEN
        UPDATE wallets
        SET balance = balance - :NEW.amount
        WHERE user_id = :NEW.user_id;
    ELSIF :NEW.txn_type = 'CREDIT' THEN
        UPDATE wallets
        SET balance = balance + :NEW.amount
        WHERE user_id = :NEW.user_id;
    END IF;
END;
/

